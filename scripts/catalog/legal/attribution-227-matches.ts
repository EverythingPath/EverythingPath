export type Attribution227MatchesFile = z.infer<
  typeof attribution227MatchesFileSchema
>;
type StoredMatch = Attribution227MatchesFile['matches'][number];
type ClassBook = z.infer<typeof classBook>;
type PcgenLineOfBook = { book: string; file: string; line: number };

/**
 * The file's matches expanded: each PCGen line with its list's book, each
 * class with its name and books. Fails on a reference the file doesn't
 * resolve and on an entry no match names.
 */
export function readAttribution227Matches(
  data: unknown,
): Attribution227Matches {
  const { listBooks, classes, matches, ...header } =
    attribution227MatchesFileSchema.parse(data);
  const usedLists = new Set<string>();
  const usedClasses = new Set<string>();
  const bookOf = (file: string) => {
    const book = listBooks[file];
    if (book === undefined)
      throw new Error(`No book for PCGen list ${file} in listBooks.`);
    usedLists.add(file);
    return book;
  };
  const line = ({ file, line }: { file: string; line: number }) => ({
    book: bookOf(file),
    file,
    line,
  });
  const classOf = (externalKey: string): ClassBook => {
    const found = classes[externalKey];
    if (!found) throw new Error(`No class ${externalKey} in classes.`);
    usedClasses.add(externalKey);
    return { externalKey, ...found };
  };
  const classList = (keys: readonly [string, ...string[]]) =>
    [classOf(keys[0]), ...keys.slice(1).map(classOf)] as const;
  const expand = (match: StoredMatch): Attribution227Match => {
    const base = {
      externalKey: match.externalKey,
      name: match.name,
      kind: match.kind,
    };
    if (match.status === 'matched') {
      const item = (evidence: (typeof match.evidence)[number]) =>
        evidence.kind === 'stored-assessment'
          ? evidence
          : { ...evidence, book: bookOf(evidence.file) };
      return {
        ...base,
        status: 'matched',
        evidence: [
          item(match.evidence[0]),
          ...match.evidence.slice(1).map(item),
        ],
        classes: match.classes.map(classOf),
      };
    }
    const { hold } = match;
    return {
      ...base,
      status: 'held',
      hold:
        hold.kind === 'association-only'
          ? { kind: hold.kind, classes: classList(hold.classes) }
          : {
              kind: hold.kind,
              candidates: [
                line(hold.candidates[0]),
                line(hold.candidates[1]),
                ...hold.candidates.slice(2).map(line),
              ],
            },
    };
  };
  const expanded = matches.map(expand);
  const unused = [
    ...Object.keys(listBooks).filter((file) => !usedLists.has(file)),
    ...Object.keys(classes).filter((key) => !usedClasses.has(key)),
  ];
  if (unused.length) throw new Error(`No match names ${unused.join(', ')}.`);
  return attribution227MatchesSchema.parse({ ...header, matches: expanded });
}

/**
 * The file form of a matches document (`readAttribution227Matches`'s
 * inverse): each list's book and each class once, sorted by key. Fails when
 * two matches give a list different books or a class different records.
 */
export function compactAttribution227Matches(
  document: Attribution227Matches,
): Attribution227MatchesFile {
  const { matches, ...header } = document;
  const listBooks = new Map<string, string>();
  const classes = new Map<string, { name: string; books: readonly string[] }>();
  const line = ({ book, file, line }: PcgenLineOfBook) => {
    const known = listBooks.get(file);
    if (known !== undefined && known !== book)
      throw new Error(`PCGen list ${file} has two books: ${known}, ${book}.`);
    listBooks.set(file, book);
    return { file, line };
  };
  const classKey = ({ externalKey, name, books }: ClassBook) => {
    const known = classes.get(externalKey);
    if (known && JSON.stringify(known) !== JSON.stringify({ name, books }))
      throw new Error(`Class ${externalKey} has two records.`);
    classes.set(externalKey, { name, books });
    return externalKey;
  };
  const compact = (match: Attribution227Match): unknown => {
    const base = {
      externalKey: match.externalKey,
      name: match.name,
      kind: match.kind,
    };
    if (match.status === 'matched')
      return {
        ...base,
        status: 'matched',
        evidence: match.evidence.map((item) => {
          if (item.kind === 'stored-assessment') return item;
          const { book, ...reference } = item;
          return { ...reference, ...line({ book, ...reference }) };
        }),
        classes: match.classes.map(classKey),
      };
    const { hold } = match;
    return {
      ...base,
      status: 'held',
      hold:
        hold.kind === 'association-only'
          ? { kind: hold.kind, classes: hold.classes.map(classKey) }
          : { kind: hold.kind, candidates: hold.candidates.map(line) },
    };
  };
  const stored = matches.map(compact);
  const sorted = <T>(map: ReadonlyMap<string, T>) =>
    Object.fromEntries(
      [...map].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)),
    );
  return attribution227MatchesFileSchema.parse({
    ...header,
    listBooks: sorted(listBooks),
    classes: sorted(classes),
    matches: stored,
  });
}

export const committedAttribution227Matches = readAttribution227Matches(data);

/** The canonical bytes' hash of a matches array (`binding.matchesSha256`). */
export const matchesSha256 = (matches: readonly Attribution227Match[]) =>
  createHash('sha256').update(JSON.stringify(matches)).digest('hex');

/** A match's books: its evidence's, then its classes' declared books, sorted. */
export function matchedBooks(
  match: MatchedAttribution227,
): readonly [string, ...string[]] {
  const [first, ...rest] = [
    ...new Set([
      ...match.evidence.flatMap((item) =>
        item.kind === 'stored-assessment' ? item.notices : [item.book],
      ),
      ...match.classes.flatMap(({ books }) => books),
    ]),
  ].sort();
  // Its evidence is non-empty, and each item names a book.
  if (first === undefined) throw new Error('A match names no book.');
  return [first, ...rest];
}

/** What the gate's lookup finds for a record (`attribution227MatchLookup`). */
export type Attribution227Lookup =
  | Attribution227Match
  /** The file lists the key under another name or kind: the import changed. */
  | { status: 'stale'; match: Attribution227Match }
  /**
   * The match reads a reviewed PCGen record that no longer applies, or the
   * file has no reviewed line for a checked one: without it the record is
   * held on its class association (`held`: the match's, or the file's held
   * row), or unmatched.
   */
  | {
      status: 'stale-reviewed-record';
      /** The stale match, or none when the file's row is held or absent. */
      match?: MatchedAttribution227;
      problem: string;
      held?: HeldAttribution227Match;
    };

type LookupEntry = {
  externalKey: string;
  name: string;
  description: string;
  detail: { kind: string };
};
/** A PCGen list's text in the pinned store, or undefined when the store lacks it. */
type PinnedListReader = (file: string) => string | undefined;
/** What the gate checks a reviewed-record match against. */
type ReviewedRecordContext = {
  grants: ClassGrants;
  /** Why the file's PCGen binding is not the pin, if it isn't. */
  pinProblem: string | undefined;
  /** Why the file's matches are not the ones it was written with, if they aren't. */
  driftProblem: string | undefined;
  /** A line of a pinned list a reviewed-record line reads (`requirePinnedPcgenLists`), if the list has it. */
  pinnedLine: (file: string, line: number) => string | undefined;
  /** The crosswalk's folders and their books (`pcgenBookFolders`). */
  bookFolders: ReadonlyMap<string, string>;
};

/** A PCGen list's text in the pinned store of the checkout at `root`, or undefined when the store lacks it. */
export const readPinnedPcgenListAt =
  (root: string): PinnedListReader =>
  (file) => {
    try {
      return readFileSync(join(pinnedPcgenRootAt(root), file), 'utf8');
    } catch {
      return undefined;
    }
  };
/** A PCGen list's text in this checkout's pinned store. */
export const readPinnedPcgenList = readPinnedPcgenListAt(thisCheckout);

const isReviewedRecordLine = (
  item: MatchedAttribution227['evidence'][number],
): item is ReviewedRecordLine =>
  item.kind === 'pcgen-fallback' && item.rule === 'reviewed-record';

/** The reviewed-record lines a matches file holds, with the key of the record each is a match of. */
export function reviewedRecordLines(
  matches: readonly Attribution227Match[],
): { externalKey: string; line: ReviewedRecordLine }[] {
  return matches.flatMap((match) =>
    match.status === 'matched'
      ? match.evidence
          .filter(isReviewedRecordLine)
          .map((line) => ({ externalKey: match.externalKey, line }))
      : [],
  );
}

/**
 * The lines of each pinned PCGen list the file's reviewed-record lines read,
 * by list file. A list the store lacks throws an error naming the list and
 * the record whose line reads it. The gate's lookup, the launch
 * verification's binding and `catalog:launch-inventory` call this, so a
 * reviewed-record match is not admitted while its line cannot be read (root,
 * 2026-11-20: that is the property; what another reader prints in that state,
 * such as a scoped release's refusal report or a stale projection, is not
 * specified). A file with no reviewed-record line needs no list.
 */
export function requirePinnedPcgenLists(
  document: Pick<Attribution227Matches, 'matches'>,
  read: PinnedListReader = readPinnedPcgenList,
): ReadonlyMap<string, readonly string[]> {
  const lists = new Map<string, readonly string[]>();
  for (const { externalKey, line } of reviewedRecordLines(document.matches)) {
    if (lists.has(line.file)) continue;
    const text = read(line.file);
    if (text === undefined)
      throw new Error(
        `The pinned PCGen list ${pinnedPcgenListPath(line.file)} is missing from the pinned store, and the matches file's reviewed-record line for ${externalKey} (${line.record.id}) is read there: restore the pinned store (git checkout -- tests/fixtures/pinned) and run the command again.`,
      );
    lists.set(line.file, text.split(/\r\n|\r|\n/));
  }
  return lists;
}

/** What the record step leaves to do when the file lacks a checked record's line. */
const regenerateMatches =
  "regenerate the matches (pnpm -s catalog:attribution-227-matches --write), the record step's next step";
/** Why a checked reviewed record's row lacks its reviewed line, naming the record. */
const withoutReviewedLine = (reviewed: ReviewedPcgenRecord, what: string) =>
  `${reviewedPcgenRecordIdentity(reviewed).id} is checked, but ${what}; ${regenerateMatches}`;

/**
 * Why a match's reviewed PCGen record no longer applies to the record the
 * gate reads, if it doesn't: the generated file cannot carry it past its
 * review. A match of a record a reviewed PCGen record names must read that
 * record's line alone, as a generation writes it; the line applies only while
 * the file was read at the PCGen pin (`pcgenPinProblem`), while the record in
 * the list is checked and is the record the match was generated from
 * (`recordProblem`: its name, description, PCGen file and KEY, ID and whole
 * hash), while the line is the pinned line it names (`pinnedLineProblem`: its
 * book, text and KEY), for a class feature while a row of the class its PCGen
 * key names grants it (`classGrantsOf`), and while the file's matches are the
 * ones it was written with (`binding.matchesSha256`).
 */
function staleReviewedRecord(
  {
    match,
    entry,
    reviewed,
  }: {
    match: MatchedAttribution227;
    entry: LookupEntry;
    /** The reviewed PCGen record that names the record, if one does. */
    reviewed: ReviewedPcgenRecord | undefined;
  },
  context: ReviewedRecordContext,
) {
  const key = entry.externalKey;
  const read = reviewedLineRead(match, entry, reviewed);
  if (read.kind === 'ordinary') return undefined;
  if (read.kind === 'problem') return read.problem;
  if (context.pinProblem) return context.pinProblem;
  if (!reviewed) return `no reviewed PCGen record names ${key}`;
  return (
    recordProblem(reviewed, entry, read.line) ??
    pinnedLineProblem(read.line, context) ??
    (match.kind === 'classFeature'
      ? ungranted(key, reviewed.pcgen.key, context.grants.get(key) ?? [])
      : undefined) ??
    context.driftProblem
  );
}

/**
 * How a match reads a reviewed line: `ordinary` for a match of a record no
 * reviewed PCGen record names, its one reviewed line, as a generation writes
 * it (the match's one evidence, for the record's name and kind), or why not.
 */
function reviewedLineRead(
  match: MatchedAttribution227,
  entry: LookupEntry,
  reviewed: ReviewedPcgenRecord | undefined,
):
  | { kind: 'ordinary' }
  | { kind: 'line'; line: ReviewedRecordLine }
  | { kind: 'problem'; problem: string } {
  const [line, ...more] = match.evidence.filter(isReviewedRecordLine);
  const problem = (text: string) => ({
    kind: 'problem' as const,
    problem: text,
  });
  if (!line) {
    if (!reviewed) return { kind: 'ordinary' };
    // A generation refuses a reviewed record whose record matches otherwise.
    const readsNoLine = `its match reads no reviewed line (${match.evidence.map(describeEvidence).join(', ')})`;
    return problem(
      reviewed.status === 'checked'
        ? withoutReviewedLine(reviewed, readsNoLine)
        : `a reviewed PCGen record names ${entry.externalKey}, but ${readsNoLine}`,
    );
  }
  if (more.length || match.evidence.length > 1)
    return problem(
      `its match reads more than its reviewed line (${match.evidence.map(({ kind }) => kind).join(', ')})`,
    );
  if (match.name !== entry.name || match.kind !== entry.detail.kind)
    return problem(
      `the match was generated for ${match.kind} "${match.name}", not ${entry.detail.kind} "${entry.name}"`,
    );
  return { kind: 'line', line };
}
const describeEvidence = (item: MatchedAttribution227['evidence'][number]) =>
  item.kind === 'pcgen-fallback' ? `${item.kind} ${item.rule}` : item.kind;

/**
 * Why a match's reviewed record is not the one it was generated from, if it
 * isn't: each field it names, then the whole record's hash, which covers the
 * rest (its evidence and its review).
 */
function recordProblem(
  reviewed: ReviewedPcgenRecord,
  entry: { externalKey: string; name: string; description: string },
  line: ReviewedRecordLine,
) {
  const key = entry.externalKey;
  if (reviewed.status !== 'checked') return `${key} is drafted`;
  if (reviewed.upstreamName !== entry.name)
    return `${key}'s record is reviewed for "${reviewed.upstreamName}", not "${entry.name}"`;
  const body = sha256Of(entry.description);
  if (body !== reviewed.descriptionSha256)
    return `${key}'s description is sha256:${body}, not the reviewed sha256:${reviewed.descriptionSha256}`;
  if (reviewed.pcgen.file !== line.file)
    return `the match reads ${line.file}:${line.line}, but ${key}'s record names ${reviewed.pcgen.file}`;
  if (reviewed.pcgen.key !== line.key)
    return `the match reads ${line.file}:${line.line} keyed "${line.key}", but ${key}'s record names "${reviewed.pcgen.key}"`;
  const identity = reviewedPcgenRecordIdentity(reviewed);
  if (identity.id !== line.record.id)
    return `the match was generated from ${line.record.id}, not ${identity.id}`;
  if (identity.sha256 !== line.record.sha256)
    return `${key}'s record is sha256:${identity.sha256}, not the sha256:${line.record.sha256} the match was generated from`;
  return undefined;
}

/**
 * Why a saved reviewed line is not the pinned PCGen line it names, if it
 * isn't: the gate reads that line in the pinned store itself, so a repair
 * that moves the line, its book or its hash and refreshes
 * `binding.matchesSha256` cannot admit on another record. Its list's book
 * comes from the crosswalk, as the matcher's does; its text has the saved
 * hash; its KEY (or column-1 name) is the saved KEY. A line number past the
 * list's end holds the match (the list itself is required:
 * `requirePinnedPcgenLists`).
 */
function pinnedLineProblem(
  line: ReviewedRecordLine,
  { pinnedLine, bookFolders }: ReviewedRecordContext,
) {
  const at = `${line.file}:${line.line}`;
  const text = pinnedLine(line.file, line.line);
  if (text === undefined)
    return `the match reads ${at}, but the pinned PCGen store's list (${pinnedPcgenListPath(line.file)}) has no line ${line.line}`;
  const book = pcgenBookOfFile(bookFolders, line.file);
  if (book !== line.book)
    return `the match reads ${at} as ${line.book}'s, but the crosswalk gives that list ${book ?? 'no book'}`;
  const hash = sha256Of(text);
  if (hash !== line.lineSha256)
    return `the match reads ${at}, whose line in the pinned PCGen store is sha256:${hash}, not the sha256:${line.lineSha256} it was generated from`;
  const object = pcgenListObject(text);
  const key = object?.key ?? object?.name;
  if (key !== line.key)
    return `the match reads ${at}, whose line in the pinned PCGen store is keyed "${key ?? '(no object)'}", not "${line.key}"`;
  return undefined;
}
const sha256Of = (text: string) =>
  createHash('sha256').update(text).digest('hex');

/** Why no row of the class a class feature's PCGen key names grants it, if none does. */
function ungranted(key: string, pcgenKey: string, granting: readonly string[]) {
  return grantingClassOf(granting, pcgenKey) === undefined
    ? `no class row grants ${key} as a feature of the class its PCGen key "${pcgenKey}" names (granted by: ${granting.join(', ') || 'none'})`
    : undefined;
}

/**
 * Why the file's reviewed lines cannot be trusted at this PCGen pin: the
 * gate reads the pinned store's lines, so a file read at another pin may name
 * a line that is not the one the store holds.
 */
function pcgenPinProblem(binding: Attribution227Matches['binding']['pcgen']) {
  const pinned = `${pcgenPin.commit} ${pcgenPin.directory}`;
  const read = `${binding.commit} ${binding.directory}`;
  return read === pinned
    ? undefined
    : `the matches file was read at PCGen ${read}, not the pinned ${pinned}`;
}

/** A matched record without its reviewed line: held on its class association. */
function heldOnClasses(
  match: MatchedAttribution227,
): HeldAttribution227Match | undefined {
  const [first, ...rest] = match.classes;
  return first
    ? {
        externalKey: match.externalKey,
        name: match.name,
        kind: match.kind,
        status: 'held',
        hold: { kind: 'association-only', classes: [first, ...rest] },
      }
    : undefined;
}

/**
 * The gate's lookup: a record's match, `stale` when the file lists its key
 * under another name or kind (the import changed since the match),
 * `stale-reviewed-record` when the match reads a reviewed PCGen record that
 * no longer applies (`staleReviewedRecord`; the committed list by default,
 * against the catalog's class grant rows and the pinned store's lines) or
 * when the file has no reviewed line for a record whose reviewed PCGen record
 * is checked (`checkedWithoutLine`: a generation always gives it one), or
 * `undefined` when it lists none.
 */
export function attribution227MatchLookup(
  document: Pick<Attribution227Matches, 'matches' | 'binding'>,
  {
    reviewedRecords = committedReviewedPcgenRecords,
    grants,
    readPinnedList = readPinnedPcgenList,
  }: {
    reviewedRecords?: readonly ReviewedPcgenRecord[];
    /** The catalog's class grant rows (`classGrantsOf`). */
    grants: ClassGrants;
    /** A pinned PCGen list (`readPinnedPcgenList`, the pinned store, by default). */
    readPinnedList?: PinnedListReader;
  },
) {
  refuseRepeatedClaims(reviewedRecords);
  const pinnedLists = requirePinnedPcgenLists(document, readPinnedList);
  const byKey = new Map(
    document.matches.map((match) => [match.externalKey, match]),
  );
  const reviewedByKey = new Map(
    reviewedRecords.map((record) => [record.externalKey, record]),
  );
  const context: ReviewedRecordContext = {
    grants,
    pinProblem: pcgenPinProblem(document.binding.pcgen),
    driftProblem:
      document.binding.matchesSha256 !== matchesSha256(document.matches)
        ? 'the matches file drifted from its binding.matchesSha256 (edited by hand?)'
        : undefined,
    pinnedLine: (file, line) => pinnedLists.get(file)?.at(line - 1),
    bookFolders: pcgenBookFolders(),
  };
  return (entry: LookupEntry): Attribution227Lookup | undefined => {
    const match = byKey.get(entry.externalKey);
    const reviewed = reviewedByKey.get(entry.externalKey);
    const unlined = checkedWithoutLine(entry.externalKey, match, reviewed);
    if (unlined) return unlined;
    if (!match) return undefined;
    const problem =
      match.status === 'matched'
        ? staleReviewedRecord({ match, entry, reviewed }, context)
        : undefined;
    if (problem !== undefined && match.status === 'matched') {
      const held = heldOnClasses(match);
      return {
        status: 'stale-reviewed-record',
        match,
        problem,
        ...(held ? { held } : {}),
      };
    }
    if (match.name !== entry.name || match.kind !== entry.detail.kind)
      return { status: 'stale', match };
    return match;
  };
}

/**
 * A checked reviewed record's row without its reviewed line, whatever the
 * file has for its key: no match, or a held one (the file generated before
 * the record step checked it, or that row copied back over its match). A
 * matched row is read by `staleReviewedRecord`.
 */
function checkedWithoutLine(
  key: string,
  match: Attribution227Match | undefined,
  reviewed: ReviewedPcgenRecord | undefined,
): Attribution227Lookup | undefined {
  if (reviewed?.status !== 'checked' || match?.status === 'matched')
    return undefined;
  if (!match)
    return {
      status: 'stale-reviewed-record',
      problem: withoutReviewedLine(
        reviewed,
        `the matches file lists no match for ${key}`,
      ),
    };
  return {
    status: 'stale-reviewed-record',
    problem: withoutReviewedLine(
      reviewed,
      `the matches file holds ${key} ${match.hold.kind}, without its reviewed line`,
    ),
    held: match,
  };
}
