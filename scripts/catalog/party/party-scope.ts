import { createHash } from 'node:crypto';
import { z } from 'zod';
import { collectReferences } from '../admission.ts';
import { jsonLines } from '../launch-inventory-document.ts';
import {
  comparePartyIds,
  partyBuildsPath,
  partyCharacterKeys,
  partyGroupKinds,
  partyRaceKinds,
  type PartyBuilds,
  type PartyGroup,
} from './party-builds.ts';

/**
 * `campaign-party-v1` (`scripts/catalog/scopes/campaign-party-v1.json`): the
 * party's builds' keys as roots and the admission gate's reference closure
 * from them (`collectReferences`, the edges `omitUnavailableDependents`
 * follows, description links included), each row with its catalog kind and
 * the characters that need it. Generated by `catalog:party-scope --write`;
 * `--check` regenerates it and compares bytes. It is not a release scope:
 * no release reads it yet.
 */
export const partyScopePath = 'scripts/catalog/scopes/campaign-party-v1.json';
export const partyScopeVersion = 'campaign-party-v1';

/**
 * The fields of a catalog entry or resource the scope reads: its key, kind
 * and name for a row, and its references (`ReferenceFields`) for the edges.
 */
const readFields = z.looseObject({
  externalKey: z.string(),
  name: z.string(),
  description: z.string(),
  detail: z.looseObject({ kind: z.string() }),
  attributionFrom: z.string().optional(),
  grantsSlots: z
    .array(z.object({ feats: z.array(z.string()).optional() }))
    .optional(),
});
export type PartyCatalogEntry = z.infer<typeof readFields>;
const keyOf = (value: unknown) =>
  typeof value === 'object' &&
  value !== null &&
  'externalKey' in value &&
  typeof value.externalKey === 'string'
    ? value.externalKey
    : 'with no key';
const unreadable = (value: unknown) => {
  const result = readFields.safeParse(value);
  return result.success ? '' : z.prettifyError(result.error);
};
/**
 * A catalog entry as a preview wrote it: refused, with its key, when a field
 * the scope reads is missing or of another type, and otherwise kept whole,
 * since release labels hash the entry as written.
 */
export const partyCatalogEntry = z.custom<PartyCatalogEntry>(
  (value) => readFields.safeParse(value).success,
  {
    error: ({ input }) =>
      `Catalog entry ${keyOf(input)} lacks what the party scope reads: ${unreadable(input)}`,
  },
);
export type PartyCatalog = {
  /** The import's entries and resources, as the gate indexes them. */
  entries: readonly PartyCatalogEntry[];
  /** The checkouts it was imported from, at their pins. */
  upstream: readonly { repository: string; commit: string }[];
};

const sha256 = (text: string) =>
  createHash('sha256').update(text).digest('hex');
const compareText = (a: string, b: string) => (a < b ? -1 : a > b ? 1 : 0);

const characterIds = z.tuple([z.string()]).rest(z.string());
const rowSchema = z.strictObject({
  key: z.string(),
  kind: z.string(),
  name: z.string(),
  characters: characterIds,
});
const edgeSchema = z.strictObject({
  from: z.string(),
  to: z.string(),
  /** `description`: reached only by a description link, as the gate follows them. */
  link: z.enum(['reference', 'description']),
});
const partyScopeSchema = z.strictObject({
  schemaVersion: z.literal(1),
  scopeVersion: z.literal(partyScopeVersion),
  binding: z.strictObject({
    builds: z.strictObject({
      path: z.literal(partyBuildsPath),
      sha256: z.string().regex(/^[a-f0-9]{64}$/),
    }),
    catalog: z.strictObject({
      upstream: z.array(
        z.strictObject({ repository: z.string(), commit: z.string() }),
      ),
      /** SHA-256 of the closure's rows (key, kind, name) and edges: what the catalog contributes. */
      graphSha256: z.string().regex(/^[a-f0-9]{64}$/),
    }),
  }),
  characters: characterIds,
  roots: z.array(
    z.strictObject({
      key: z.string(),
      group: z.string(),
      characters: characterIds,
    }),
  ),
  rows: z.array(rowSchema),
  edges: z.array(edgeSchema),
});
export type PartyScope = z.infer<typeof partyScopeSchema>;
export type PartyScopeRow = PartyScope['rows'][number];

/**
 * The scope of `builds` (whose file bytes are `buildsBytes`) on `catalog`.
 * Refuses a root the catalog doesn't carry or whose kind its group doesn't
 * allow. A key a closure row references but the catalog doesn't carry is no
 * row and no edge, as the gate's dependents ignore it.
 */
export function buildPartyScope({
  builds,
  buildsBytes,
  catalog,
}: {
  builds: PartyBuilds;
  buildsBytes: string;
  catalog: PartyCatalog;
}): PartyScope {
  const entries = new Map(
    catalog.entries.map((entry) => [entry.externalKey, entry]),
  );
  const roots = partyRoots(builds, entries);
  const { characters, edges } = closure(roots, entries);
  const rows = [...characters]
    .sort(([a], [b]) => compareText(a, b))
    .map(([key, ids]) => {
      const entry = entries.get(key);
      if (!entry) throw new Error(`Missing closure entry ${key}.`);
      return {
        key,
        kind: entry.detail.kind,
        name: entry.name,
        characters: sortIds(ids),
      };
    });
  const edgeList = [...edges.values()].sort(
    (a, b) => compareText(a.from, b.from) || compareText(a.to, b.to),
  );
  return partyScopeSchema.parse({
    schemaVersion: 1,
    scopeVersion: partyScopeVersion,
    binding: {
      builds: { path: partyBuildsPath, sha256: sha256(buildsBytes) },
      catalog: {
        upstream: [...catalog.upstream]
          .map(({ repository, commit }) => ({ repository, commit }))
          .sort((a, b) => compareText(a.repository, b.repository)),
        graphSha256: partyGraphSha256({ rows, edges: edgeList }),
      },
    },
    characters: sortIds(builds.characters.map(({ id }) => id)),
    roots: [...roots]
      .sort(([a], [b]) => compareText(a, b))
      .map(([key, { group, characters }]) => ({
        key,
        group,
        characters: sortIds(characters),
      })),
    rows,
    edges: edgeList,
  });
}

/** Every row the roots reach, with the characters that need it, and the edges walked. */
function closure(
  roots: ReadonlyMap<string, { characters: readonly string[] }>,
  entries: ReadonlyMap<string, PartyCatalogEntry>,
) {
  const characters = new Map<string, Set<string>>();
  const edges = new Map<string, PartyScope['edges'][number]>();
  for (const [key, root] of roots) {
    const stack = [key];
    const seen = new Set<string>();
    while (stack.length) {
      const current = stack.pop() ?? '';
      if (seen.has(current)) continue;
      seen.add(current);
      const needed = characters.get(current) ?? new Set();
      for (const id of root.characters) needed.add(id);
      characters.set(current, needed);
      for (const edge of outgoing(entries.get(current), entries)) {
        edges.set(`${edge.from}\0${edge.to}`, edge);
        stack.push(edge.to);
      }
    }
  }
  return { characters, edges };
}

/** The builds' keys, each with its group and characters; refuses a key the catalog lacks or whose kind its group doesn't allow. */
function partyRoots(
  builds: PartyBuilds,
  entries: ReadonlyMap<string, PartyCatalogEntry>,
) {
  const roots = new Map<string, { group: PartyGroup; characters: string[] }>();
  const problems: string[] = [];
  for (const character of builds.characters)
    for (const [group, key] of partyCharacterKeys(character)) {
      const entry = entries.get(key);
      const allowed: readonly string[] =
        group === 'race' ? partyRaceKinds : partyGroupKinds[group];
      if (!entry)
        problems.push(`${character.id} ${group}: ${key} is not in the catalog`);
      else if (!allowed.includes(entry.detail.kind))
        problems.push(
          `${character.id} ${group}: ${key} (${entry.name}) is a ${entry.detail.kind}`,
        );
      const root = roots.get(key) ?? { group, characters: [] };
      root.characters.push(character.id);
      roots.set(key, root);
    }
  if (problems.length)
    throw new Error(`Party builds keys refused: ${problems.join('; ')}.`);
  return roots;
}

/** The edges the gate follows out of `entry`, to keys the catalog carries. */
function outgoing(
  entry: PartyCatalogEntry | undefined,
  entries: ReadonlyMap<string, PartyCatalogEntry>,
): PartyScope['edges'] {
  if (!entry) return [];
  const all = collectReferences(entry);
  const structural = new Set(collectReferences({ ...entry, description: '' }));
  return all
    .filter((key) => entries.has(key) && key !== entry.externalKey)
    .map((to) => ({
      from: entry.externalKey,
      to,
      link: structural.has(to) ? 'reference' : 'description',
    }));
}

function sortIds(ids: Iterable<string>): [string, ...string[]] {
  const [first, ...rest] = [...new Set(ids)].sort(comparePartyIds);
  if (first === undefined) throw new Error('A scope row needs a character.');
  return [first, ...rest];
}

/** What the catalog contributes to a scope: its rows' identities and its edges. */
export function partyGraphSha256({
  rows,
  edges,
}: Pick<PartyScope, 'rows' | 'edges'>) {
  return sha256(
    JSON.stringify({
      rows: rows.map(({ key, kind, name }) => [key, kind, name]),
      edges: edges.map(({ from, to, link }) => [from, to, link]),
    }),
  );
}

/**
 * The stored form, `campaign-party-records-v4`: the v4 stable-key rule of the
 * launch inventory (`launch-inventory-document.ts`) in one self-contained
 * file. Each row is a record under its content key, the first 64 bits of
 * SHA-256 over its stored JSON in base64url, and `rows` lists `{"$r": key}`
 * references in key order, so a changed row changes only its own lines. A
 * record whose JSON doesn't hash to its key, a missing reference or an unused
 * record is refused on reading.
 */
export const partyScopeEncoding = 'campaign-party-records-v4';
const recordKey = (json: string) =>
  createHash('sha256')
    .update(json)
    .digest()
    .subarray(0, 8)
    .toString('base64url');
const storedSchema = z.strictObject({
  encoding: z.literal(partyScopeEncoding),
  value: z
    .object({ rows: z.array(z.strictObject({ $r: z.string() })) })
    .passthrough(),
  records: z.record(z.string().regex(/^[A-Za-z0-9_-]{11}$/), rowSchema),
});

export function encodePartyScope(scope: PartyScope) {
  const records: Record<string, PartyScopeRow> = {};
  const rows = scope.rows.map((row) => {
    const key = recordKey(JSON.stringify(row));
    const prior = records[key];
    if (prior && JSON.stringify(prior) !== JSON.stringify(row))
      throw new Error(`Party scope record key collision ${key}.`);
    records[key] = row;
    return { $r: key };
  });
  return {
    encoding: partyScopeEncoding,
    value: { ...scope, rows },
    records: Object.fromEntries(
      Object.entries(records).sort(([a], [b]) => compareText(a, b)),
    ),
  };
}

export function decodePartyScope(document: unknown): PartyScope {
  const stored = storedSchema.parse(document);
  const unused = new Set(Object.keys(stored.records));
  const rows = stored.value.rows.map(({ $r }) => {
    const record = stored.records[$r];
    if (!record) throw new Error(`Missing party scope record ${$r}.`);
    if (recordKey(JSON.stringify(record)) !== $r)
      throw new Error(`Changed party scope record ${$r}.`);
    unused.delete($r);
    return record;
  });
  if (unused.size)
    throw new Error(`Unused party scope records: ${[...unused].join(', ')}.`);
  return partyScopeSchema.parse({ ...stored.value, rows });
}

/** One JSON value per line for each list and the records table. */
export function serializePartyScope(
  document: ReturnType<typeof encodePartyScope>,
) {
  return jsonLines(document, document.records);
}

/** The committed bytes for a scope. */
export function partyScopeBytes(scope: PartyScope) {
  return serializePartyScope(encodePartyScope(scope));
}

/**
 * Why the committed scope file isn't the bytes the generator writes now:
 * the builds file changed, the catalog's closure changed, or the file itself
 * was edited or is unreadable. Empty when current.
 */
export function partyScopeDrift({
  committed,
  regenerated,
}: {
  committed: string | undefined;
  regenerated: PartyScope;
}): string[] {
  if (committed === undefined) return ['the scope file is missing'];
  if (committed === partyScopeBytes(regenerated)) return [];
  let stored: PartyScope;
  try {
    stored = decodePartyScope(JSON.parse(committed));
  } catch (error) {
    return [
      `the scope file is unreadable: ${error instanceof Error ? error.message : String(error)}`,
    ];
  }
  const reasons = [];
  const hasBuildsFileChanged =
    stored.binding.builds.sha256 !== regenerated.binding.builds.sha256;
  if (hasBuildsFileChanged) reasons.push('the builds file changed');
  // New builds have a new closure; only the same builds tell a catalog change.
  if (
    JSON.stringify(stored.binding.catalog.upstream) !==
      JSON.stringify(regenerated.binding.catalog.upstream) ||
    (!hasBuildsFileChanged &&
      stored.binding.catalog.graphSha256 !==
        regenerated.binding.catalog.graphSha256)
  )
    reasons.push('the catalog changed');
  if (!reasons.length)
    reasons.push('the scope file differs from what the generator writes');
  return reasons;
}
